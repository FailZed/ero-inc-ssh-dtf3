def set_cell_shading(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def set_table_borders(table):
    tbl = table._tbl
    tbl_pr = tbl.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        element = OxmlElement(f"w:{edge}")
        element.set(qn("w:val"), "single")
        element.set(qn("w:sz"), "6")
        element.set(qn("w:space"), "0")
        element.set(qn("w:color"), "B7C4D4")
        borders.append(element)
    tbl_pr.append(borders)


def add_bullets(cell, items):
    cell.text = ""
    for item in items:
        p = cell.add_paragraph(item, style="List Bullet")
        p.paragraph_format.space_after = Pt(2)


def build_docx():
    doc = Document()
    section = doc.sections[0]
    section.top_margin = Pt(42)
    section.bottom_margin = Pt(42)
    section.left_margin = Pt(46)
    section.right_margin = Pt(46)

    styles = doc.styles
    styles["Normal"].font.name = "Arial"
    styles["Normal"].font.size = Pt(10.5)
    styles["Heading 1"].font.name = "Arial"
    styles["Heading 2"].font.name = "Arial"

    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title.add_run("Пролог: таймлайны и мини-главы")
    run.bold = True
    run.font.size = Pt(18)

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    subtitle_run = subtitle.add_run(
        "Рабочая структура для редактирования сценария по независимым смысловым блокам"
    )
    subtitle_run.italic = True
    subtitle_run.font.size = Pt(10.5)

    doc.add_paragraph(
        "Ниже сценарий разбит на короткие редактируемые модули. Каждый модуль можно переписывать отдельно, "
        "не разваливая общую драматургию. Длительности ориентировочные и нужны только как монтажный ориентир."
    )

    doc.add_heading("Ключевые опоры", level=1)
    for note in STRUCTURE_NOTES:
        doc.add_paragraph(note, style="List Bullet")

    doc.add_heading("Таймлайны", level=1)
    for entry in TIMELINES:
        doc.add_heading(f"{entry['id']} · {entry['title']}", level=2)

        meta = doc.add_table(rows=2, cols=3)
        meta.alignment = WD_TABLE_ALIGNMENT.CENTER
        meta.style = "Table Grid"
        set_table_borders(meta)
        headers = ["Охват", "Оценка длительности", "Функция сцены"]
        values = [entry["scope"], entry["duration"], entry["purpose"]]
        for idx, header in enumerate(headers):
            meta.cell(0, idx).text = header
            set_cell_shading(meta.cell(0, idx), "DCE6F1")
            meta.cell(1, idx).text = values[idx]

        doc.add_paragraph()

        table = doc.add_table(rows=2, cols=3)
        table.alignment = WD_TABLE_ALIGNMENT.CENTER
        table.style = "Table Grid"
        set_table_borders(table)
        labels = ["Ключевые биты", "Что удобно править отдельно", "Примечание"]
        for idx, label in enumerate(labels):
            table.cell(0, idx).text = label
            set_cell_shading(table.cell(0, idx), "EAF2F8")

        add_bullets(table.cell(1, 0), entry["beats"])
        add_bullets(table.cell(1, 1), entry["editable"])
        table.cell(1, 2).text = entry["notes"]

        doc.add_paragraph()

    doc.add_section(WD_SECTION.NEW_PAGE)
    doc.add_heading("Сводка по переработке", level=1)
    summary = [
        "Если нужно быстро менять темп, сначала трогать `TL-02`, `TL-08`, `TL-13`.",
        "Если нужно усиливать мистику, работать через `TL-01`, `TL-03`, `TL-05`.",
        "Если нужно усиливать романтическую линию, работать через `TL-11` и `TL-12`.",
        "Если нужно усилить социальный конфликт мира, расширять `TL-06`, `TL-08`, `TL-10`.",
        "Если сценарий будет интерактивным, первым делом нужно дописать полноценную ветку `убежать` из `TL-09`.",
    ]
    for item in summary:
        doc.add_paragraph(item, style="List Bullet")

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    doc.save(DOCX_PATH)


